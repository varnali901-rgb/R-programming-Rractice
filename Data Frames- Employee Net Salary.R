enumber=1:10
ename=c("E1","E2","E3","E4","E5","E6","E7","E8","E9","E10")
esalary=c(20000,20000,20000,20000,20000,50000,20000,20000,20000,20000)
df=data.frame("EMPLOYEE_NUMBER"=enumber,"EMPLOYEE_NAME"=ename,"BASIC_SALARY"=esalary)

df$DAILY_ALLOWANCE=(df$BASIC_SALARY*0.35)

df$HOUSE_RENT_ALLOWANCE=(df$BASIC_SALARY*0.4)

df$CITY_COMPENSATION_ALLOWANCE=(df$BASIC_SALARY*0.05)

df$PROVIDENT_FUND=(df$BASIC_SALARY*0.12) + df$DAILY_ALLOWANCE

df$NET_SALARY=(df$BASIC_SALARY + df$DAILY_ALLOWANCE + df$HOUSE_RENT_ALLOWANCE + df$CITY_COMPENSATION_ALLOWANCE) -df$PROVIDENT_FUND

print(df)
