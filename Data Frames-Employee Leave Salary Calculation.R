enumber=1:10
ename=c("E1","E2","E3","E4","E5","E6","E7","E8","E9","E10")
esalary=c(20000,20000,60000,20000,20000,50000,20000,20000,80000,20000)
tdays=200
leaves=c(10,3,5,6,15,0,8,12,2,21)
df=data.frame("EMPLOYEE_NUMBER"=enumber,"EMPLOYEE_NAME"=ename,"TOTAL_MONTHLY_SALARY"=esalary,"TOTAL_DAYS"=tdays,"LEAVES_TAKEN"=leaves)

df$SALARY_PER_DAY=(df$TOTAL_MONTHLY_SALARY/df$TOTAL_DAYS)

df$SALARY_PER_MONTH=(df$SALARY_PER_DAY*(df$TOTAL_DAYS-df$LEAVES_TAKEN))

df$SALARY_DEDUCTED=(df$TOTAL_MONTHLY_SALARY-df$SALARY_PER_MONTH)

print(df)
